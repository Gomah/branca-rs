/**
 * Builds the Rust core to WebAssembly and generates the bindings consumed by src/internal/wasm.ts:
 *
 *   cargo build (wasm32-unknown-unknown) → wasm-bindgen (web target) → wasm-opt → base64 module
 *
 * Output lands in src/generated/ (git-ignored): branca.js, branca.d.ts, branca_bg.wasm and
 * wasm-bytes.ts. Requires `cargo`, the wasm32-unknown-unknown target and a wasm-bindgen CLI whose
 * version matches the wasm-bindgen crate in Cargo.lock.
 */
import { $ } from "bun";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const crate = "branca-core";
const target = "wasm32-unknown-unknown";
const outDir = resolve(root, "src/generated");
const outName = "branca";
const wasmOpt = resolve(root, "node_modules/.bin/wasm-opt");

$.cwd(root);

console.log("▸ cargo build --release --target", target);
await $`cargo build --release --target ${target} -p ${crate}`;

const lock = await Bun.file(resolve(root, "Cargo.lock")).text();
const wanted = /name = "wasm-bindgen"\nversion = "([^"]+)"/.exec(lock)?.[1];
if (!wanted) throw new Error("Could not find the wasm-bindgen crate in Cargo.lock");

let installed: string | undefined;
try {
  installed = (await $`wasm-bindgen --version`.quiet().text()).trim().split(/\s+/).at(-1);
} catch {
  installed = undefined;
}
if (installed !== wanted) {
  console.error(
    installed
      ? `wasm-bindgen CLI ${installed} does not match the wasm-bindgen crate ${wanted} in Cargo.lock.`
      : "The wasm-bindgen CLI is not installed.",
  );
  console.error(
    `Install the matching version with:\n\n  cargo install wasm-bindgen-cli --locked --version ${wanted}\n`,
  );
  process.exit(1);
}

console.log("▸ wasm-bindgen", wanted);
const input = `target/${target}/release/${crate.replaceAll("-", "_")}.wasm`;
await $`wasm-bindgen ${input} --out-dir ${outDir} --out-name ${outName} --target web --typescript --omit-default-module-path --remove-name-section --remove-producers-section`;

const wasmPath = resolve(outDir, `${outName}_bg.wasm`);
const before = (await Bun.file(wasmPath).bytes()).byteLength;

console.log("▸ wasm-opt -Oz");
try {
  await $`${wasmOpt} -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext --enable-mutable-globals --enable-multivalue --enable-reference-types --strip-debug --strip-producers -o ${wasmPath} ${wasmPath}`;
} catch (error) {
  console.warn(`wasm-opt failed, shipping the unoptimized module: ${String(error)}`);
}

const bytes = await Bun.file(wasmPath).bytes();
await Bun.write(
  resolve(outDir, "wasm-bytes.ts"),
  `// Generated by scripts/build-wasm.ts from ${outName}_bg.wasm. Do not edit.\n` +
    `export const wasmBase64: string =\n  "${Buffer.from(bytes).toString("base64")}";\n`,
);
console.log(`✔ ${outName}_bg.wasm: ${before} → ${bytes.byteLength} bytes; wrote src/generated/wasm-bytes.ts`);
