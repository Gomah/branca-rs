/**
 * Runs bench/branca.bench.ts under Bun and Node, then writes bench/RESULTS.md and refreshes the
 * table in the README's Performance section (between the bench:start / bench:end markers).
 *
 *   bun run bench:report
 */
import { $ } from "bun";
import { resolve } from "node:path";
import type { BenchSummary } from "./branca.bench.ts";

const root = resolve(import.meta.dir, "..");
const benchFile = resolve(root, "bench/branca.bench.ts");
const resultsFile = resolve(root, "bench/RESULTS.md");
const readmeFile = resolve(root, "README.md");
$.cwd(root);

async function runWith(runtime: "bun" | "node"): Promise<BenchSummary> {
  console.error(`▸ ${runtime}: running benchmarks (about a minute)…`);
  const stdout = await $`${runtime} ${benchFile} --json`.text();
  const line = stdout.trim().split("\n").at(-1) ?? "";
  return JSON.parse(line) as BenchSummary;
}

function formatNs(ns: number): string {
  if (ns < 1_000) return `${ns.toFixed(0)} ns`;
  if (ns < 1_000_000) return `${(ns / 1_000).toFixed(2)} µs`;
  return `${(ns / 1_000_000).toFixed(2)} ms`;
}

function table(summary: BenchSummary): string {
  const groups = new Map<string, Map<string, number>>();
  for (const r of summary.results) {
    const byName = groups.get(r.group) ?? new Map<string, number>();
    byName.set(r.name, r.avgNs);
    groups.set(r.group, byName);
  }
  const rows = [...groups].map(([name, byName]) => {
    const rs = byName.get("branca-rs") ?? Number.NaN;
    const js = byName.get("branca-js") ?? Number.NaN;
    return `| ${name} | ${formatNs(rs)} | ${formatNs(js)} | ${(js / rs).toFixed(1)}× |`;
  });
  return ["| Operation | branca-rs | branca-js | Speedup |", "| --- | ---: | ---: | ---: |", ...rows].join(
    "\n",
  );
}

function heading(summary: BenchSummary): string {
  const runtime = summary.runtime === "bun" ? "Bun" : "Node.js";
  return `${runtime} ${summary.version} (${summary.cpu}, ${summary.arch})`;
}

const summaries: BenchSummary[] = [];
for (const runtime of ["bun", "node"] as const) {
  // Sequential on purpose: running both at once would make them compete for the CPU.
  // oxlint-disable-next-line no-await-in-loop
  summaries.push(await runWith(runtime));
}

const today = new Date().toISOString().slice(0, 10);
const results = `# Benchmark results

Generated by \`bun run bench:report\` on ${today}. Compares branca-rs with
[branca-js](https://github.com/tuupola/branca-js), the original implementation published on npm as \`branca\`
(libsodium.js for the AEAD, base-x for base62). Payloads are printable ASCII of the given size; each cell is
the mean time per operation reported by [mitata](https://github.com/evanwashere/mitata), and "Speedup" is
branca-js ÷ branca-rs.

${summaries.map((s) => `## ${heading(s)}\n\n${table(s)}\n`).join("\n")}`;
await Bun.write(resultsFile, results);

const start = "<!-- bench:start -->";
const end = "<!-- bench:end -->";
const readme = await Bun.file(readmeFile).text();
if (readme.includes(start) && readme.includes(end)) {
  const block = `${start}\n\n${summaries.map((s) => `**${heading(s)}**\n\n${table(s)}\n`).join("\n")}\n${end}`;
  await Bun.write(
    readmeFile,
    readme.slice(0, readme.indexOf(start)) + block + readme.slice(readme.indexOf(end) + end.length),
  );
}

await $`${resolve(root, "node_modules/.bin/oxfmt")} README.md bench/RESULTS.md`.quiet();
console.log(results);
console.error(`✔ wrote bench/RESULTS.md and refreshed the README Performance section`);
